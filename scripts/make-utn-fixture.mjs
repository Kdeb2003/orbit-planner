// Builds the public test fixture from the real PDF: positioned text + painted rectangles of a few
// selected weeks (plus the course legend). No PDF bytes, file names or metadata are copied.
// Usage: node scripts/make-utn-fixture.mjs "<timetable.pdf>"
import fs from 'node:fs'
import * as pdfjs from 'pdfjs-dist/legacy/build/pdf.mjs'
import { extractDocumentLayouts } from '../src/timetable/utn/pdfLayout.ts'
import { extractWeekTables } from '../src/timetable/utn/tables.ts'

const WEEKS = [1, 4, 5, 8, 12, 13, 14, 20, 21, 23, 25]
const pdfPath = process.argv[2]
if (!pdfPath || !fs.existsSync(pdfPath)) {
  console.error('Usage: node scripts/make-utn-fixture.mjs "<timetable.pdf>"')
  process.exit(1)
}
const doc = await pdfjs.getDocument({ data: new Uint8Array(fs.readFileSync(pdfPath)), standardFontDataUrl: 'node_modules/pdfjs-dist/standard_fonts/' }).promise
const layouts = await extractDocumentLayouts(doc)
const tables = extractWeekTables(layouts)

// Minimal representative fixture: only the cards of the courses the tests talk about stay; every other
// course's cell (text and painted rectangle) is dropped, so the public file does not re-publish the
// whole timetable. Table structure (titles, headers, grid, slot labels, dates) is kept intact.
const KEEP = new Set([
  'W26M-AINBA', 'W26M-RBTAD', 'W26M-NLGAD', 'W26M-NLUAD', 'W26M-MMFAD', 'W26M-LLMAD', 'W26M-INSIN', 'W26M-Deutsch A2', // the user's selection
  'W26M-MOBBA', 'W26M-CLDAD', 'W26M-PSYIN', // neighbours on the tricky 20 Oct day
  'W26M-LiT', 'W26M-REGEL', 'W26M-ETHIN', 'W26M-Deutsch A1.1', // project work, joint excursion card, Saturday groups
  'W26M-GSPKC', 'W26M-PMLAD', // group "B,C" and numbered variants
])
const chosen = tables.filter((t) => WEEKS.includes(t.semesterWeek))
const keepRegions = new Map() // page -> [{y0,y1}]
const cardsByPage = new Map() // page -> cards of the chosen weeks
for (const t of chosen) {
  for (const r of t.regions) keepRegions.set(r.page, [...(keepRegions.get(r.page) ?? []), { y0: r.y0 - 1.5, y1: r.y1 + 1.5 }])
  for (const c of t.cards) cardsByPage.set(c.source.page, [...(cardsByPage.get(c.source.page) ?? []), c])
}
const isCardRect = (r) => Math.min(r.x1 - r.x0, r.y1 - r.y0) >= 8 && r.fill !== '#ffffff' && !['#203864', '#d9e2f3', '#1f4e78'].includes(r.fill)
const inBox = (t, b) => (t.x0 + t.x1) / 2 >= b.x0 - 0.5 && (t.x0 + t.x1) / 2 <= b.x1 + 0.5 && t.y >= b.y0 - 0.5 && t.y <= b.y1 + 0.5

const pages = []
for (const l of layouts) {
  if (l.texts.some((t) => t.str.trim() === 'Course number')) {
    // legend: header + rows of the kept codes only
    const rows = l.texts.filter((t) => KEEP.has(t.str.trim())).map((t) => t.y)
    const nearRow = (y) => rows.some((ry) => Math.abs(ry - y) < 2.5)
    pages.push({
      ...l,
      texts: l.texts.filter((t) => ['Course number', 'Course title', 'Color'].includes(t.str.trim()) || nearRow(t.y)),
      rects: l.rects.filter((r) => r.x0 <= 400 || nearRow((r.y0 + r.y1) / 2 + 3)),
    })
    continue
  }
  const regions = keepRegions.get(l.page)
  if (!regions) continue
  const inside = (y) => regions.some((r) => y >= r.y0 && y <= r.y1)
  const cards = cardsByPage.get(l.page) ?? []
  const kept = cards.filter((c) => c.courseCodes.some((code) => KEEP.has(code)))
  const keptBoxes = kept.map((c) => c.source.bbox)
  const allBoxes = cards.map((c) => c.source.bbox)
  const texts = l.texts.filter((t) => inside(t.y) && (!allBoxes.some((b) => inBox(t, b)) || keptBoxes.some((b) => inBox(t, b))))
  const baseRects = l.rects.filter((r) => inside((r.y0 + r.y1) / 2) && !isCardRect(r))
  const cardRects = kept.map((c) => ({ x0: c.source.bbox.x0, y0: c.source.bbox.y0, x1: c.source.bbox.x1, y1: c.source.bbox.y1, fill: c.fill }))
  pages.push({ ...l, texts, rects: [...baseRects, ...cardRects] })
}
const out = {
  description: 'Minimal page layouts (positioned text and painted cells) derived from the UTN timetable WiSe 2026/27, preliminary as of 28 September 2026: only the cards of the courses used in tests; weeks: ' + WEEKS.join(', ') + '. Generated by scripts/make-utn-fixture.mjs.',
  weeks: WEEKS,
  pages,
}
fs.mkdirSync('src/timetable/utn/__fixtures__', { recursive: true })
fs.writeFileSync('src/timetable/utn/__fixtures__/utn-wise2627-layouts.json', JSON.stringify(out))
console.log('pages', pages.length, 'texts', pages.reduce((n, p) => n + p.texts.length, 0), 'rects', pages.reduce((n, p) => n + p.rects.length, 0), 'bytes', fs.statSync('src/timetable/utn/__fixtures__/utn-wise2627-layouts.json').size)
